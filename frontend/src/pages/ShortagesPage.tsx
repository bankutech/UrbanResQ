import React from 'react';
import { AlertTriangle, AlertOctagon, TrendingDown, CheckCircle2, ShieldAlert, Package } from 'lucide-react';
import { useFetch } from '../hooks/useFetch';
import { DataTable } from '../components/DataTable';
import { Panel, StatusBadge, StatCard, Skeleton, PageHeader, Button } from '../components/ui';

export default function ShortagesPage() {
  const { data, loading, error, reload } = useFetch<any[]>('/shortages');

  const shortages = data || [];
  const critical = shortages.filter((s) => s.severity === 'CRITICAL').length;
  const warning = shortages.filter((s) => s.severity === 'WARNING').length;
  const totalDeficit = shortages.reduce((acc, s) => acc + (Number(s.deficit) || 0), 0);

  return (
    <div className="space-y-4 font-sans">
      <PageHeader
        title="Automated Supply Deficit & Shortage Engine"
        subtitle="Automatic shortage triggers generated by stored procedures and minimum safety stock violations"
        freshness="Shortage Detection Engine Active"
        action={
          <Button variant="secondary" size="sm" onClick={reload}>
            RE-EVALUATE DEFICITS
          </Button>
        }
      />

      {/* Top Telemetry KPI Cards */}
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-3">
        <StatCard 
          label="Critical Deficits" 
          value={critical} 
          tone={critical > 0 ? "critical" : "normal"}
          icon={AlertOctagon}
          sub="Zero or exhausted buffers"
        />
        <StatCard 
          label="Depletion Warnings" 
          value={warning} 
          tone={warning > 0 ? "warning" : "normal"}
          icon={TrendingDown}
          sub="Under safety threshold"
        />
        <StatCard 
          label="Gross Unit Deficit" 
          value={totalDeficit.toLocaleString()} 
          tone={totalDeficit > 0 ? "warning" : "normal"}
          icon={Package}
          sub="Units required to restock"
        />
        <StatCard 
          label="Trigger Mechanism" 
          value="AUTOMATED" 
          tone="normal"
          icon={ShieldAlert}
          sub="ACID DB triggers active"
        />
      </div>

      <Panel title="Active Inventory Shortage Incident Lines">
        <DataTable
          loading={loading}
          error={error}
          onRetry={reload}
          rows={shortages}
          emptyMessage="Zero open shortages — all depot inventories satisfy minimum safety thresholds."
          columns={[
            { 
              header: 'Resource Type', 
              render: (s: any) => (
                <div>
                  <div className="font-semibold text-eoc-text">{s.resource_type_name}</div>
                  <div className="text-[10px] font-mono text-eoc-muted uppercase">
                    {s.category?.replace(/_/g, ' ')}
                  </div>
                </div>
              ) 
            },
            { 
              header: 'Impact Sector', 
              render: (s: any) => (
                <span className="font-mono text-xs text-eoc-muted">
                  {s.zone_name || s.location_label || 'Metropolitan Area'}
                </span>
              ) 
            },
            { 
              header: 'Required Units', 
              render: (s: any) => (
                <span className="font-mono text-xs tabular-nums text-eoc-text font-bold">
                  {Number(s.required_quantity).toLocaleString()}
                </span>
              ) 
            },
            { 
              header: 'Available Units', 
              render: (s: any) => (
                <span className="font-mono text-xs tabular-nums text-eoc-muted">
                  {Number(s.available_quantity).toLocaleString()}
                </span>
              ) 
            },
            { 
              header: 'Net Deficit', 
              render: (s: any) => (
                <span className="font-mono text-xs font-bold text-red-400 tabular-nums">
                  -{Number(s.deficit).toLocaleString()}
                </span>
              ) 
            },
            { 
              header: 'Affected Calls', 
              render: (s: any) => (
                <span className="font-mono text-xs tabular-nums">
                  {s.affected_requests} calls
                </span>
              ) 
            },
            { 
              header: 'Deficit Severity', 
              render: (s: any) => <StatusBadge value={s.severity} /> 
            },
          ]}
        />
      </Panel>
    </div>
  );
}
